#!/usr/bin/env python3
"""Regenerate the front end's built-in demo data from skill/examples/sample-vault, then copy the
front end to demo/index.html. Run it after changing the sample vault or skill/app/index.html.

    python3 tools/sync_demo.py          # rewrite + copy, prints what changed
    python3 tools/sync_demo.py --check  # exit 1 if the demo data or demo/index.html is out of date (for CI / before commit)

The demo data lives between the DEMO-DATA markers in skill/app/index.html; it is only used when the page
is opened without serve.py (no write token), so it never touches a real vault.
"""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APP, DEMO, SAMPLE = ROOT / "skill/app/index.html", ROOT / "demo/index.html", ROOT / "skill/examples/sample-vault"
BEGIN, END = "/* DEMO-DATA:BEGIN", "/* DEMO-DATA:END */"
DROP = ("schema", "created", "updated")


def load_dir(d):
    out = []
    for f in sorted((SAMPLE / d).glob("*.json")):
        o = json.loads(f.read_text(encoding="utf-8"))
        for k in DROP:
            o.pop(k, None)
        out.append(o)
    return out


def block():
    cfg = json.loads((SAMPLE / "config.json").read_text(encoding="utf-8"))
    j = lambda o: json.dumps(o, ensure_ascii=False)
    rows = lambda xs: "[\n" + ",\n".join(" " + j(x) for x in xs) + "\n]"
    return (f"{BEGIN} — generated by tools/sync_demo.py from skill/examples/sample-vault; edit the sample vault, not this block */\n"
            f"const CARDS={rows(load_dir('experiences'))};\n"
            f"const DOCS={rows(load_dir('applications'))};\n"
            f"const RESUMES={rows(load_dir('resumes'))};\n"
            f"if(!LIVE)Object.assign(VAULT_CFG.profile,{j(cfg.get('profile') or {})});  // demo only: the sample person, so the sheet isn't blank\n"
            f"{END}")


def main():
    check = "--check" in sys.argv
    s = APP.read_text(encoding="utf-8")
    if BEGIN in s:
        a, b = s.index(BEGIN), s.index(END) + len(END)
    else:  # first run: the hand-written demo data from `const CARDS=[` to the RESUMES text init line
        a = s.index("const CARDS=[")
        init = s.index("RESUMES.forEach(r=>r.sections.forEach(s=>(s.items||[]).forEach(it=>{if(!it.text){")
        b = s.index("\n", init)
    new = s[:a] + block() + s[b:]
    stale_app, stale_demo = new != s, (not DEMO.exists()) or DEMO.read_text(encoding="utf-8") != new
    if check:
        print("demo data:", "OUT OF DATE" if stale_app else "ok", "| demo/index.html:", "OUT OF DATE" if stale_demo else "ok")
        sys.exit(1 if (stale_app or stale_demo) else 0)
    APP.write_text(new, encoding="utf-8")
    DEMO.write_text(new, encoding="utf-8")
    print(("UPDATED demo data" if stale_app else "demo data already current") + " · demo/index.html " + ("synced" if stale_demo else "already identical"))


if __name__ == "__main__":
    main()
